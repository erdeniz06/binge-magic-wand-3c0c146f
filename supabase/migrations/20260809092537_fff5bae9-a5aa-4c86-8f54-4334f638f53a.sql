CREATE TABLE public.imdb_ratings (
  tmdb_id integer PRIMARY KEY,
  imdb_id text NOT NULL,
  title text NOT NULL,
  rating numeric NOT NULL,
  votes integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT ON public.imdb_ratings TO anon;
GRANT SELECT ON public.imdb_ratings TO authenticated;
GRANT ALL ON public.imdb_ratings TO service_role;
ALTER TABLE public.imdb_ratings ENABLE ROW LEVEL SECURITY;
CREATE POLICY imdb_ratings_public_read ON public.imdb_ratings FOR SELECT TO anon, authenticated USING (true);
CREATE OR REPLACE FUNCTION public.update_updated_at_column() RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$ BEGIN NEW.updated_at = now(); RETURN NEW; END; $$;
CREATE TRIGGER update_imdb_ratings_updated_at BEFORE UPDATE ON public.imdb_ratings FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();
